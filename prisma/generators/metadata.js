const { generatorHandler } = require("@prisma/generator-helper");
const fs = require("node:fs");
const path = require("node:path");

generatorHandler({
  onManifest() {
    return {
      prettyName: "Prisma CASL Metadata Generator",
      defaultOutput: "../src/generated/prisma",
    };
  },
  async onGenerate(options) {
    const modelsMeta = {};
    const relationFieldsByModel = {};
    const propertyFieldsByModel = {};
    const modelFieldsByModel = {};
    const subjectFieldsByModel = {};

    for (const model of options.dmmf.datamodel.models) {
      const relationFields = {};
      for (const field of model.fields) {
        if (field.kind === "object" && field.relationName) {
          relationFields[field.name] = {
            name: field.name,
            type: field.type,
            kind: field.kind,
            isList: field.isList,
            isRequired: field.isRequired,
            relationName: field.relationName,
            relationFromFields: field.relationFromFields ?? [],
            relationToFields: field.relationToFields ?? [],
          };
        }
      }
      relationFieldsByModel[model.name] = relationFields;

      const propertyFields = {};
      for (const field of model.fields) {
        if (!(field.kind === "object" && field.relationName)) {
          let relatedRelationName = null;
          for (const relField of model.fields) {
            if (relField.kind === "object" && relField.relationName && relField.relationFromFields?.includes(field.name)) {
              relatedRelationName = relField.name;
              break;
            }
          }
          propertyFields[field.name] = relatedRelationName;
        }
      }
      propertyFieldsByModel[model.name] = propertyFields;

      const allFields = Object.keys(propertyFields);
      modelFieldsByModel[model.name] = allFields;
      subjectFieldsByModel[model.name] = [...allFields, ...Object.keys(relationFields)];

      modelsMeta[model.name] = { allFields, relationFields, propertyFields };
    }

    const outputContent = "// Auto-generated by prisma-extension-casl metadata generator\n// DO NOT EDIT MANUALLY\n\nexport const modelsMeta = " + JSON.stringify(modelsMeta, null, 2) + " as const\n\nexport const relationFieldsByModel = " + JSON.stringify(relationFieldsByModel, null, 2) + " as const\nexport const propertyFieldsByModel = " + JSON.stringify(propertyFieldsByModel, null, 2) + " as const\nexport const modelFieldsByModel = " + JSON.stringify(modelFieldsByModel, null, 2) + " as const\nexport const subjectFieldsByModel = " + JSON.stringify(subjectFieldsByModel, null, 2) + " as const\n";

    const outputDir = options.generator.output.value;
    if (!outputDir) throw new Error("No output directory defined for metadata generator");

    fs.mkdirSync(outputDir, { recursive: true });
    fs.writeFileSync(path.join(outputDir, "metadata.ts"), outputContent);
  },
});
