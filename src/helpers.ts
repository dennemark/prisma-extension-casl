/** Minimal field metadata matching what the generator produces */
export interface ModelFieldMeta {
    name: string
    type: string
    kind: string
    isList: boolean
    isRequired: boolean
    relationName?: string
    relationFromFields?: readonly string[]
    relationToFields?: readonly string[]
}

/** Metadata for all models, keyed by model name */
export type ModelsMeta = Record<string, {
    allFields: readonly string[]
    relationFields: Record<string, ModelFieldMeta>
    propertyFields: Record<string, string | null>
}>

